#!/bin/sh
#
# Container entry point for the Hapkido Laravel application.
#
# The script prepares the writable directories, makes sure the SQLite database
# exists, publishes the compiled front-end assets for the nginx container,
# optionally runs the migrations, warms up the Laravel caches for the
# production environment and finally starts the given command (php-fpm).
#
# The script is written for a POSIX shell (Alpine BusyBox ash).
#
set -e

APP_DIR="${APP_DIR:-/var/www/html}"
APP_USER="${APP_USER:-app}"
APP_GROUP="${APP_GROUP:-app}"
PUBLIC_SHARE_DIR="${PUBLIC_SHARE_DIR:-/srv/public}"
MIGRATION_TEMPLATE_DIR="${MIGRATION_TEMPLATE_DIR:-/opt/app/database}"
KEY_FILE="${KEY_FILE:-$APP_DIR/storage/app/app.key}"

log() {
    printf '[entrypoint] %s\n' "$*"
}

warn() {
    printf '[entrypoint] WARNING: %s\n' "$*" >&2
}

cd "$APP_DIR"

# ---------------------------------------------------------------------------
# Helper functions
# ---------------------------------------------------------------------------

# Run a command as the unprivileged application user. Every file that is
# generated by the application therefore belongs to that user.
as_app_user() {
    if [ "$(id -u)" = "0" ] && command -v su-exec > /dev/null 2>&1; then
        su-exec "$APP_USER:$APP_GROUP" "$@"
    else
        "$@"
    fi
}

# Create a directory when it is missing and make sure that it is writable.
prepare_dir() {
    dir="$1"
    if [ ! -d "$dir" ]; then
        mkdir -p "$dir"
    fi
    if [ "$(id -u)" = "0" ]; then
        chown -R "$APP_USER:$APP_GROUP" "$dir" 2> /dev/null || true
    fi
    chmod ug+rwX "$dir" 2> /dev/null || true
}

# ---------------------------------------------------------------------------
# 1. Writable directories
# ---------------------------------------------------------------------------
log "preparing the writable directories"

prepare_dir "$APP_DIR/bootstrap/cache"
prepare_dir "$APP_DIR/storage/app"
prepare_dir "$APP_DIR/storage/app/public"
prepare_dir "$APP_DIR/storage/framework/cache"
prepare_dir "$APP_DIR/storage/framework/cache/data"
prepare_dir "$APP_DIR/storage/framework/cache/laravel-excel"
prepare_dir "$APP_DIR/storage/framework/sessions"
prepare_dir "$APP_DIR/storage/framework/views"
prepare_dir "$APP_DIR/storage/logs"
prepare_dir "$APP_DIR/database"

# ---------------------------------------------------------------------------
# 2. SQLite database
# ---------------------------------------------------------------------------
DB_FILE="${DB_DATABASE:-$APP_DIR/database/database.sqlite}"
case "$DB_FILE" in
    /*) ;;
    *) DB_FILE="$APP_DIR/$DB_FILE" ;;
esac

if [ ! -f "$DB_FILE" ]; then
    log "creating the SQLite database at $DB_FILE"
    mkdir -p "$(dirname "$DB_FILE")"
    touch "$DB_FILE"
fi

if [ "$(id -u)" = "0" ]; then
    chown "$APP_USER:$APP_GROUP" "$DB_FILE" 2> /dev/null || true
fi
chmod 664 "$DB_FILE" 2> /dev/null || true

# The database directory is backed by a named volume. Refresh the migrations
# from the pristine copy of the image so that new migrations are picked up
# after a rebuild.
if [ -d "$MIGRATION_TEMPLATE_DIR/migrations" ]; then
    mkdir -p "$APP_DIR/database/migrations"
    cp -a "$MIGRATION_TEMPLATE_DIR/migrations/." "$APP_DIR/database/migrations/"
    if [ "$(id -u)" = "0" ]; then
        chown -R "$APP_USER:$APP_GROUP" "$APP_DIR/database" 2> /dev/null || true
    fi
fi

# ---------------------------------------------------------------------------
# 3. Application key
# ---------------------------------------------------------------------------
if [ -z "${APP_KEY:-}" ]; then
    if [ -f "$KEY_FILE" ]; then
        APP_KEY="$(cat "$KEY_FILE")"
        export APP_KEY
        log "reusing the application key from $KEY_FILE"
    else
        APP_KEY="base64:$(php -r 'echo base64_encode(random_bytes(32));')"
        export APP_KEY
        printf '%s' "$APP_KEY" > "$KEY_FILE"
        if [ "$(id -u)" = "0" ]; then
            chown "$APP_USER:$APP_GROUP" "$KEY_FILE" 2> /dev/null || true
        fi
        chmod 600 "$KEY_FILE" 2> /dev/null || true
        log "generated a new application key"
    fi
else
    log "using the application key from the environment"
fi

# ---------------------------------------------------------------------------
# 4. Publish the front-end assets for the nginx container
# ---------------------------------------------------------------------------
if [ -d "$PUBLIC_SHARE_DIR" ]; then
    log "publishing the public assets to $PUBLIC_SHARE_DIR"
    rm -rf "$PUBLIC_SHARE_DIR/build"
    cp -a "$APP_DIR/public/." "$PUBLIC_SHARE_DIR/"
    if [ -d "$APP_DIR/storage/app/public" ]; then
        rm -rf "$PUBLIC_SHARE_DIR/storage"
        cp -a "$APP_DIR/storage/app/public" "$PUBLIC_SHARE_DIR/storage"
    fi
fi

# ---------------------------------------------------------------------------
# 5. Laravel caches
# ---------------------------------------------------------------------------
if [ "${APP_ENV:-production}" = "production" ]; then
    log "caching the Laravel configuration"
    as_app_user php artisan config:cache --no-interaction || warn "the configuration could not be cached"

    log "caching the Laravel routes"
    as_app_user php artisan route:cache --no-interaction || warn "the routes could not be cached"

    log "caching the compiled views"
    as_app_user php artisan view:cache --no-interaction || warn "the views could not be cached"
fi

# ---------------------------------------------------------------------------
# 6. Public storage symlink
# ---------------------------------------------------------------------------
if [ ! -e "$APP_DIR/public/storage" ]; then
    as_app_user php artisan storage:link --no-interaction || warn "the storage symlink could not be created"
fi

# ---------------------------------------------------------------------------
# 7. Database migrations
# ---------------------------------------------------------------------------
if [ "${RUN_MIGRATIONS:-false}" = "true" ]; then
    log "running the database migrations"
    as_app_user php artisan migrate --force --no-interaction
fi

# ---------------------------------------------------------------------------
# 8. Start the container
# ---------------------------------------------------------------------------
if [ "$#" -eq 0 ]; then
    set -- php-fpm
fi

# The official PHP image allows flags such as "-a" to be passed directly.
if [ "${1#-}" != "$1" ]; then
    set -- php "$@"
fi

log "starting: $*"

if [ "$(id -u)" = "0" ] && command -v su-exec > /dev/null 2>&1; then
    exec su-exec "$APP_USER:$APP_GROUP" "$@"
fi

exec "$@"
